#!/usr/bin/env python3
"""Regenerate src/basis_data.cpp (built-in basis sets) in Gaussian94 format.

The numerical data originate from the Basis Set Exchange / EMSL library; this
script reads them through PySCF's bundled copy (pip install pyscf==2.6.2) so the
embedded strings can be reproduced exactly.

    python tools/gen_basis_data.py > src/basis_data.cpp
"""
from pyscf.gto import basis

BASES = [("sto-3g", "sto-3g"), ("6-31g", "6-31g"), ("6-31g*", "6-31g*")]
SYMBOLS = ["H", "He", "Li", "Be", "B", "C", "N", "O", "F", "Ne",
           "Na", "Mg", "Al", "Si", "P", "S", "Cl", "Ar"]
LETTER = "SPDFGHI"


def element_block(name, sym):
    lines = [f"{sym}     0"]
    for shell in basis.load(name, sym):
        l, prims = shell[0], shell[1:]
        ncontr = len(prims[0]) - 1
        for c in range(ncontr):  # general contractions -> separate segmented shells
            lines.append(f"{LETTER[l]}   {len(prims)}   1.00")
            for p in prims:
                lines.append(f"  {p[0]:>18.10E}  {p[1 + c]:>18.10E}")
    lines.append("****")
    return "\n".join(lines)


def main():
    out = ["// Generated by tools/gen_basis_data.py -- do not edit by hand.",
           "// Data: Basis Set Exchange (via PySCF 2.6.2), Gaussian94 format.",
           '#include "basis_data.hpp"', "", "namespace qk::detail {", "",
           "const std::vector<BuiltinBasisEntry>& builtin_basis_table() {",
           "  static const std::vector<BuiltinBasisEntry> table = {"]
    for key, name in BASES:
        for z, sym in enumerate(SYMBOLS, start=1):
            out.append(f'    {{"{key}", {z}, R"G94(')
            out.append(element_block(name, sym))
            out.append(')G94"},')
    out += ["  };", "  return table;", "}", "", "}  // namespace qk::detail", ""]
    print("\n".join(out))


if __name__ == "__main__":
    main()
